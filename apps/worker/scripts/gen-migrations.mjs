#!/usr/bin/env node
// Bundles migrations/*.sql into src/db/migrations.gen.ts so the Worker can create and upgrade its
// own D1 schema on first use (src/db/migrate.ts, D-051). Runs as part of `pnpm build`.
//
//   node scripts/gen-migrations.mjs           write the file
//   node scripts/gen-migrations.mjs --check   fail if the file is out of date (CI)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../migrations/", import.meta.url);
const out = new URL("../src/db/migrations.gen.ts", import.meta.url);

/** Splits a migration into statements, dropping `--` comments; quotes are respected. */
function statements(sql) {
  const result = [];
  let current = "";
  let quote = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (quote !== null) {
      current += ch;
      if (ch === quote) quote = null;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      current += ch;
    } else if (ch === "-" && sql[i + 1] === "-") {
      while (i < sql.length && sql[i] !== "\n") i++;
      current += "\n";
    } else if (ch === ";") {
      result.push(current);
      current = "";
    } else {
      current += ch;
    }
  }
  if (quote !== null) throw new Error("unterminated quote in migration");
  result.push(current);
  return result
    .map((s) =>
      s
        .split("\n")
        .map((line) => line.trimEnd())
        .filter((line) => line.trim() !== "")
        .join("\n"),
    )
    .filter((s) => s !== "");
}

const migrations = readdirSync(dir)
  .filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f))
  .sort()
  .map((file) => ({
    name: file,
    statements: statements(readFileSync(new URL(file, dir), "utf8")),
  }));

const text = `// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit.
export interface Migration {
  readonly name: string;
  readonly statements: readonly string[];
}

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch (e) {
    if (e.code !== "ENOENT") throw e;
  }
  if (current !== text) {
    console.error(
      "src/db/migrations.gen.ts is out of date: run `pnpm --filter @zk2fa/worker migrations`",
    );
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
